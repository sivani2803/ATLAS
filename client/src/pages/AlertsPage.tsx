import React, { useState, useEffect } from 'react';
import {
  AlertTriangle,
  CheckCircle2,
  Clock,
  Filter,
  Search,
  MessageSquare,
  ShieldAlert,
  Radio,
  MapPin,
  RefreshCw,
  Mail,
  Smartphone,
  X,
  Info
} from 'lucide-react';
import { api } from '../services/api';
import { useAuth } from '../context/AuthContext';
import { RiskBadge } from '../components/RiskBadge';
import { Alert, Location } from '../types';

export const AlertsPage: React.FC = () => {
  const { isOperator } = useAuth();
  const [alerts, setAlerts] = useState<Alert[]>([]);
  const [locations, setLocations] = useState<Location[]>([]);
  const [loading, setLoading] = useState<boolean>(true);
  const [refreshing, setRefreshing] = useState<boolean>(false);
  
  // Filters
  const [severityFilter, setSeverityFilter] = useState<string>('all');
  const [statusFilter, setStatusFilter] = useState<string>('all');
  const [locationFilter, setLocationFilter] = useState<string>('all');

  // Modal
  const [selectedAlert, setSelectedAlert] = useState<Alert | null>(null);
  const [notes, setNotes] = useState<string>('');
  const [submitting, setSubmitting] = useState<boolean>(false);

  const fetchAlerts = async () => {
    try {
      const [alertRes, locRes] = await Promise.all([
        api.getAlerts({
          severity: severityFilter,
          status: statusFilter,
          location: locationFilter
        }),
        api.getLocations()
      ]);
      setAlerts(alertRes.alerts || []);
      setLocations(locRes || []);
    } catch (err) {
      console.error('Failed to fetch alerts:', err);
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  };

  useEffect(() => {
    fetchAlerts();
  }, [severityFilter, statusFilter, locationFilter]);

  const handleAcknowledge = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!selectedAlert) return;
    setSubmitting(true);
    try {
      await api.acknowledgeAlert(selectedAlert._id, notes);
      setSelectedAlert(null);
      setNotes('');
      fetchAlerts();
    } catch (err: any) {
      alert(`Acknowledgement failed: ${err.message}`);
    } finally {
      setSubmitting(false);
    }
  };

  const handleResolve = async (id: string) => {
    if (!window.confirm('Mark this alert as resolved?')) return;
    try {
      await api.resolveAlert(id);
      fetchAlerts();
    } catch (err: any) {
      alert(`Resolution failed: ${err.message}`);
    }
  };

  return (
    <div className="mx-auto max-w-7xl px-4 sm:px-6 lg:px-8 py-8 space-y-6">
      
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-200 pb-5">
        <div>
          <div className="flex items-center gap-2">
            <ShieldAlert size={16} className="text-orange-600" />
            <span className="text-xs font-mono font-semibold uppercase tracking-wider text-orange-700">
              Hazard Threshold Event Center (Demo Mode)
            </span>
          </div>
          <h1 className="mt-1 text-2xl font-extrabold tracking-tight text-slate-900 sm:text-3xl">
            Simulated Hazard Alerts &amp; Threshold Log
          </h1>
        </div>

        <button
          onClick={() => { setRefreshing(true); fetchAlerts(); }}
          disabled={refreshing}
          className="flex items-center gap-1.5 rounded-lg border border-slate-200 bg-white px-3 py-1.5 text-xs font-semibold text-slate-700 hover:bg-slate-50 transition-colors shadow-xs"
        >
          <RefreshCw size={13} className={refreshing ? 'animate-spin' : ''} />
          <span>Refresh Feed</span>
        </button>
      </div>

      {/* Demo Integrity Notice Banner */}
      <div className="rounded-xl border border-amber-300 bg-amber-50/80 p-3.5 text-xs text-amber-950">
        <div className="flex items-start gap-2.5">
          <Info size={16} className="text-amber-700 shrink-0 mt-0.5" />
          <div className="text-[11px] leading-relaxed">
            <strong className="text-amber-900 font-semibold">Demonstration Scenario Data:</strong> The threshold breach records 
            and event notifications cataloged below are generated by synthetic sensor pulses for interface and heuristic 
            evaluation. They do not represent live civil defense emergency warnings or certified field evacuations.
          </div>
        </div>
      </div>


      {/* Filter Row */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
        {/* Severity */}
        <select
          value={severityFilter}
          onChange={(e) => setSeverityFilter(e.target.value)}
          className="rounded-xl border border-slate-300 bg-white px-3 py-2 text-xs text-slate-700 focus:border-orange-500 focus:outline-none shadow-xs"
        >
          <option value="all">All Severities</option>
          <option value="Critical">Critical Priority</option>
          <option value="High">High Hazard</option>
          <option value="Moderate">Moderate</option>
          <option value="Low">Low</option>
        </select>

        {/* Status */}
        <select
          value={statusFilter}
          onChange={(e) => setStatusFilter(e.target.value)}
          className="rounded-xl border border-slate-300 bg-white px-3 py-2 text-xs text-slate-700 focus:border-orange-500 focus:outline-none shadow-xs"
        >
          <option value="all">All Lifecycle States</option>
          <option value="active">Active (Requires Attention)</option>
          <option value="acknowledged">Acknowledged by Operator</option>
          <option value="resolved">Resolved</option>
        </select>

        {/* Location */}
        <select
          value={locationFilter}
          onChange={(e) => setLocationFilter(e.target.value)}
          className="rounded-xl border border-slate-300 bg-white px-3 py-2 text-xs text-slate-700 focus:border-orange-500 focus:outline-none shadow-xs"
        >
          <option value="all">All Monitored Slopes</option>
          {locations.map((l) => (
            <option key={l._id} value={l._id}>{l.name} ({l.code})</option>
          ))}
        </select>
      </div>

      {/* Alerts List */}
      {loading ? (
        <div className="flex h-64 items-center justify-center text-xs text-slate-500">
          Querying alert logs...
        </div>
      ) : alerts.length === 0 ? (
        <div className="rounded-2xl border border-slate-200 bg-white p-12 text-center text-slate-500 shadow-sm">
          <CheckCircle2 size={36} className="mx-auto mb-3 text-emerald-600" />
          <h3 className="text-base font-bold text-slate-900">No Alarms Found</h3>
          <p className="mt-1 text-xs">No active or historical alerts match the current filter selection.</p>
        </div>
      ) : (
        <div className="space-y-3">
          {alerts.map((alert) => {
            const isCritical = alert.severity === 'Critical';
            const isHigh = alert.severity === 'High';

            return (
              <div
                key={alert._id}
                className={`rounded-2xl border p-5 shadow-sm transition-all ${
                  isCritical
                    ? 'border-rose-200 bg-rose-50/70'
                    : isHigh
                    ? 'border-orange-200 bg-orange-50/70'
                    : 'border-slate-200 bg-white'
                }`}
              >
                <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-3">
                  <div className="space-y-1">
                    <div className="flex flex-wrap items-center gap-2">
                      <RiskBadge level={alert.severity} size="sm" showScore={false} />
                      <span className="font-mono text-xs text-slate-600">
                        {alert.location?.name} ({alert.location?.code})
                      </span>
                      <span
                        className={`rounded px-2 py-0.5 text-[10px] font-mono uppercase font-bold border ${
                          alert.status === 'active'
                            ? 'bg-rose-100 text-rose-800 border-rose-300'
                            : alert.status === 'acknowledged'
                            ? 'bg-amber-100 text-amber-800 border-amber-300'
                            : 'bg-emerald-100 text-emerald-800 border-emerald-300'
                        }`}
                      >
                        {alert.status}
                      </span>
                    </div>

                    <h3 className="text-sm sm:text-base font-bold text-slate-900 pt-1">
                      {alert.title}
                    </h3>
                  </div>

                  {/* Timestamps */}
                  <div className="text-left sm:text-right text-[11px] text-slate-500 font-mono">
                    <div className="flex items-center sm:justify-end gap-1">
                      <Clock size={12} />
                      <span>Triggered: {new Date(alert.createdAt).toLocaleString()}</span>
                    </div>
                    {alert.acknowledgedAt && (
                      <div className="text-amber-800 font-medium mt-0.5">
                        Ack: {new Date(alert.acknowledgedAt).toLocaleTimeString()} by {alert.acknowledgedBy?.name || 'Operator'}
                      </div>
                    )}
                  </div>
                </div>

                <p className="mt-3 text-xs leading-relaxed text-slate-700">
                  {alert.message}
                </p>

                {/* Trigger Details & Delivery Channel Badges */}
                <div className="mt-4 flex flex-wrap items-center justify-between gap-3 border-t border-slate-100 pt-3 text-xs">
                  <div className="flex items-center gap-3 text-[11px] text-slate-600 font-mono">
                    <span>
                      Condition: <span className="text-slate-900 font-bold">{alert.triggerCondition?.metric}</span>
                    </span>
                    {alert.triggerCondition?.threshold !== undefined && (
                      <span>
                        Threshold: <span className="text-orange-700 font-semibold">{alert.triggerCondition.threshold}</span>
                      </span>
                    )}
                    {alert.triggerCondition?.observedValue !== undefined && (
                      <span>
                        Observed: <span className="text-rose-700 font-bold">{alert.triggerCondition.observedValue}</span>
                      </span>
                    )}
                  </div>

                  {/* Delivery Status */}
                  <div className="flex items-center gap-3 text-[10px] font-mono">
                    <span className="flex items-center gap-1 text-emerald-700 font-medium" title="Delivered to in-app stream">
                      <span className="h-1.5 w-1.5 rounded-full bg-emerald-600" />
                      In-App: Live
                    </span>
                    <span
                      className={`flex items-center gap-1 ${
                        alert.deliveryStatus.email === 'sent' ? 'text-emerald-700 font-medium' : 'text-slate-500'
                      }`}
                      title={alert.deliveryStatus.email === 'sent' ? 'Email sent' : 'SendGrid credentials unconfigured'}
                    >
                      <Mail size={12} />
                      Email: {alert.deliveryStatus.email}
                    </span>
                    <span
                      className={`flex items-center gap-1 ${
                        alert.deliveryStatus.sms === 'sent' ? 'text-emerald-700 font-medium' : 'text-slate-500'
                      }`}
                      title={alert.deliveryStatus.sms === 'sent' ? 'SMS dispatched' : 'Twilio credentials unconfigured'}
                    >
                      <Smartphone size={12} />
                      SMS: {alert.deliveryStatus.sms}
                    </span>
                  </div>

                  {/* Action Buttons */}
                  {isOperator && alert.status !== 'resolved' && (
                    <div className="flex items-center gap-2">
                      {alert.status === 'active' && (
                        <button
                          onClick={() => { setSelectedAlert(alert); setNotes(''); }}
                          className="rounded-lg border border-amber-300 bg-amber-50 px-3 py-1.5 text-xs font-semibold text-amber-800 hover:bg-amber-100 shadow-xs"
                        >
                          Acknowledge
                        </button>
                      )}
                      <button
                        onClick={() => handleResolve(alert._id)}
                        className="rounded-lg border border-emerald-300 bg-emerald-50 px-3 py-1.5 text-xs font-semibold text-emerald-800 hover:bg-emerald-100 shadow-xs"
                      >
                        Resolve
                      </button>
                    </div>
                  )}
                </div>

                {alert.acknowledgementNotes && (
                  <div className="mt-3 rounded-lg bg-amber-50/80 p-2.5 text-xs text-amber-900 border border-amber-200">
                    <span className="font-semibold block text-[10px] uppercase text-amber-800">
                      Operator Incident Log:
                    </span>
                    {alert.acknowledgementNotes}
                  </div>
                )}
              </div>
            );
          })}
        </div>
      )}

      {/* Acknowledge Modal */}
      {selectedAlert && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/40 backdrop-blur-xs p-4">
          <div className="w-full max-w-md rounded-2xl border border-slate-200 bg-white p-6 shadow-2xl">
            <div className="flex items-center justify-between border-b border-slate-100 pb-3">
              <h3 className="text-sm font-bold text-slate-900 uppercase tracking-wider">
                Acknowledge Alert
              </h3>
              <button onClick={() => setSelectedAlert(null)} className="text-slate-400 hover:text-slate-700">
                <X size={16} />
              </button>
            </div>

            <form onSubmit={handleAcknowledge} className="mt-4 space-y-4 text-xs">
              <div>
                <p className="text-slate-900 font-semibold">{selectedAlert.title}</p>
                <p className="text-slate-600 text-[11px] mt-1">{selectedAlert.message}</p>
              </div>

              <div>
                <label className="block font-medium text-slate-700 mb-1">
                  Operator Acknowledgement Notes / Dispatch Actions:
                </label>
                <textarea
                  rows={3}
                  required
                  placeholder="e.g. Geotechnical field squad mobilized, local emergency authorities notified..."
                  value={notes}
                  onChange={(e) => setNotes(e.target.value)}
                  className="w-full rounded-lg border border-slate-300 bg-slate-50/50 px-3 py-2 text-slate-900 placeholder-slate-400 focus:bg-white focus:border-orange-500 focus:outline-none"
                />
              </div>

              <div className="flex justify-end gap-2 pt-2">
                <button
                  type="button"
                  onClick={() => setSelectedAlert(null)}
                  className="rounded-lg border border-slate-200 px-3 py-1.5 text-slate-600 hover:bg-slate-50"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={submitting}
                  className="rounded-lg bg-orange-600 px-4 py-1.5 font-semibold text-white hover:bg-orange-700 disabled:opacity-50 shadow-xs"
                >
                  Confirm Acknowledgement
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

    </div>
  );
};
